import { execFile } from 'node:child_process';
import { mkdir, readFile, readdir, rename, rm, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { promisify } from 'node:util';
import { isValidPagePath } from '../api/pageFields.mjs';
import isValidHostname from './isValidHostname.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const DEFAULT_OUTPUT_DIR = join(ROOT, 'dist', 'kroy', 'nginx');
const DEFAULT_SITES_ROOT = join(ROOT, 'dist', 'sites');
const HEADER = '# Generated by Kroy. Do not edit.';
const RELEASE_PATTERN = /^\d{17}$/;
const execFileAsync = promisify(execFile);

function quote(value) {
    return `"${String(value).replaceAll('\\', '\\\\').replaceAll('"', '\\"')}"`;
}

function locationPath(path) {
    return path === '/' ? '/' : path.replace(/\/$/, '');
}

function buildServer(siteSlug, domains, routing, {
    siteRoot,
    sitesRoot,
    upstream,
    listen,
    releaseId,
}) {
    const redirects = routing.redirects.map(({ from, to }, index) => [
        `    location = ${quote(locationPath(from))} {`,
        `        return 301 ${quote(to)};`,
        '    }',
    ].join('\n'));
    const gone = routing.gone.map((path) => [
        `    location = ${quote(locationPath(path))} {`,
        '        return 410;',
        '    }',
    ].join('\n'));
    const root = join(sitesRoot, siteRoot);

    return [
        `server {`,
        `    listen ${listen};`,
        `    server_name ${domains.map(quote).join(' ')};`,
        `    root ${quote(root)};`,
        `    index index.html;`,
        `    # Kroy release: ${releaseId || 'staging'}`,
        '',
        '    location ~ ^/(admin|auth|api|public|static|uploads)(/|$) {',
        `        proxy_pass http://${upstream};`,
        '        proxy_set_header Host $http_host;',
        '        proxy_set_header X-Real-IP $remote_addr;',
        '        proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;',
        '        proxy_set_header X-Forwarded-Proto $scheme;',
        '    }',
        '',
        `    location ^~ /_kroy/releases/ {`,
        `        alias ${quote(sitesRoot + '/' + siteSlug + '/')};`,
        '        try_files $uri =404;',
        '    }',
        '',
        ...redirects,
        ...gone,
        '    location / {',
        '        try_files $uri $uri/ $uri/index.html =404;',
        '    }',
        '}',
        '',
    ].join('\n');
}

export async function renderNginxConfig(siteSlug, domains, options = {}) {
    const {
        routing,
        routingPath,
        siteRoot = siteSlug,
        sitesRoot = process.env.NGINX_SITES_ROOT || DEFAULT_SITES_ROOT,
        upstream = process.env.NGINX_UPSTREAM || '127.0.0.1:3000',
        listen = process.env.NGINX_LISTEN || '80',
        releaseId,
    } = options;
    const data = routing || JSON.parse(await readFile(routingPath, 'utf8'));
    if (releaseId !== undefined && !RELEASE_PATTERN.test(releaseId)) throw new Error(`Некорректный ID релиза: ${releaseId}`);
    if (!Array.isArray(domains) || domains.length === 0 || domains.some((domain) => !isValidHostname(domain))) throw new Error(`Некорректные домены сайта ${siteSlug}`);
    if (!Array.isArray(data.redirects) || !data.redirects.every((item) => item?.status === 301 && isValidPagePath(item.from) && isValidPagePath(item.to))) throw new Error(`Некорректные правила redirect сайта ${siteSlug}`);
    if (!Array.isArray(data.gone) || !data.gone.every(isValidPagePath)) throw new Error(`Некорректные правила gone сайта ${siteSlug}`);
    return buildServer(siteSlug, domains, data, { siteRoot, sitesRoot, upstream, listen, releaseId });
}

export default async function generateNginxConfig(siteSlug, domains, options = {}) {
    const outputDir = options.outputDir || process.env.NGINX_CONFIG_DIR || DEFAULT_OUTPUT_DIR;
    const outputPath = join(outputDir, 'nginx.conf');
    const fragmentPath = join(outputDir, `${siteSlug}.conf`);
    const temporaryPath = `${outputPath}.tmp`;
    const temporaryFragmentPath = `${fragmentPath}.tmp`;
    const server = await renderNginxConfig(siteSlug, domains, options);
    await mkdir(outputDir, { recursive: true });
    const fragments = [];
    for (const name of (await readdir(outputDir)).filter((name) => name.endsWith('.conf') && name !== 'nginx.conf' && name !== `${siteSlug}.conf`).sort()) {
        const content = await readFile(join(outputDir, name), 'utf8');
        if (content.startsWith(HEADER)) fragments.push(content);
    }
    const config = [
        HEADER,
        `pid ${options.pidFile || process.env.NGINX_PID_FILE || join(outputDir, 'nginx.pid')};`,
        'events {}',
        'http {',
        '    access_log off;',
        '    error_log stderr notice;',
        '    include /etc/nginx/mime.types;',
        '    default_type application/octet-stream;',
        '    sendfile on;',
        `    server { listen ${options.listen || process.env.NGINX_LISTEN || '80'} default_server; server_name _; return 404; }`,
        ...[...fragments, server].map((value) => value.split('\n').map((line) => `    ${line}`).join('\n')),
        '}',
        '',
    ].join('\n');
    await writeFile(temporaryFragmentPath, `${HEADER}\n${server}`);
    await writeFile(temporaryPath, config);
    try {
        await execFileAsync(options.nginxBin || process.env.NGINX_BIN || 'nginx', ['-t', '-c', temporaryPath], { cwd: ROOT });
        await rename(temporaryFragmentPath, fragmentPath);
        await rename(temporaryPath, outputPath);
    } finally {
        await rm(temporaryFragmentPath, { force: true });
        await rm(temporaryPath, { force: true });
    }
    return outputPath;
}
