import assert from 'node:assert/strict';
import { mkdtemp, readFile, rm } from 'node:fs/promises';
import test from 'node:test';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import generateNginxConfig, { renderNginxConfig } from './generateNginxConfig.mjs';

test('renders Nginx proxy, release and routing rules', async () => {
    const config = await renderNginxConfig('demo', ['demo.example.test'], {
        routing: {
            redirects: [{ status: 301, from: '/old', to: '/new' }],
            gone: ['/removed'],
        },
        siteRoot: 'demo/20261025010101000',
        sitesRoot: '/srv/sites',
        upstream: '127.0.0.1:3000',
        listen: '8080',
        releaseId: '20261025010101000',
    });

    assert.match(config, /listen 8080/);
    assert.match(config, /server_name "demo\.example\.test"/);
    assert.match(config, /proxy_set_header Host \$http_host/);
    assert.match(config, /proxy_set_header X-Real-IP \$remote_addr/);
    assert.match(config, /proxy_set_header X-Forwarded-For \$proxy_add_x_forwarded_for/);
    assert.match(config, /proxy_set_header X-Forwarded-Proto \$kroy_forwarded_proto/);
    assert.match(config, /alias "\/srv\/sites\/demo\//);
    assert.match(config, /return 301 "\/new"/);
    assert.match(config, /return 410/);
});

test('writes a server fragment for an existing Nginx include', async () => {
    const directory = await mkdtemp(join(tmpdir(), 'kroy-nginx-'));
    try {
        const { configPath, fragmentPath } = await generateNginxConfig('demo', ['demo.example.test'], {
            outputDir: directory,
            routing: { redirects: [], gone: [] },
            releaseId: '20261025010101000',
        });
        const fragment = await readFile(fragmentPath, 'utf8');
        assert.equal(fragmentPath, join(directory, 'sites', 'demo.conf'));
        assert.equal(configPath, join(directory, 'nginx.conf'));
        assert.match(fragment, /^# Generated by Kroy/m);
        assert.match(fragment, /^server \{/m);
        assert.doesNotMatch(fragment, /events \{|http \{/);
        const mainConfig = await readFile(configPath, 'utf8');
        assert.match(mainConfig, /worker_processes 1/);
        assert.match(mainConfig, /include .*sites\/\*\.conf/);
        assert.match(mainConfig, /listen 127\.0\.0\.1:8080 default_server/);
        assert.match(mainConfig, /return 404/);
    } finally {
        await rm(directory, { recursive: true, force: true });
    }
});

test('resolves relative site and config roots from the project root', async () => {
    const directory = await mkdtemp(join(tmpdir(), 'kroy-nginx-'));
    try {
        const { fragmentPath } = await generateNginxConfig('demo', ['demo.example.test'], {
            outputDir: directory,
            sitesRoot: 'dist/sites',
            routing: { redirects: [], gone: [] },
        });
        const fragment = await readFile(fragmentPath, 'utf8');
        assert.match(fragment, new RegExp(`root "${resolve(process.cwd(), 'dist/sites')}/demo"`));
        assert.equal(fragmentPath, join(directory, 'sites', 'demo.conf'));
    } finally {
        await rm(directory, { recursive: true, force: true });
    }
});
