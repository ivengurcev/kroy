import { execFile } from 'node:child_process';
import { mkdir, readFile, readdir, rename, rm, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { promisify } from 'node:util';
import { isValidPagePath } from '../api/pageFields.mjs';
import isValidHostname from './isValidHostname.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const ROUTING_DIR = join(ROOT, 'dist', 'kroy', 'routing');
const OUTPUT_DIR = join(ROOT, 'dist', 'kroy', 'caddy');
const execFileAsync = promisify(execFile);
const FRAGMENT_HEADER = '# Generated by Kroy. Do not edit.';

function quote(value) {
    return `"${value.replaceAll('\\', '\\\\').replaceAll('"', '\\"')}"`;
}

export default async function generateCaddyConfig(
    siteSlug,
    domains,
    {
        routingPath = join(ROUTING_DIR, `${siteSlug}.json`),
        siteRoot = siteSlug,
        releaseId,
    } = {}
) {
    if (releaseId !== undefined && !/^\d{17}$/.test(releaseId)) {
        throw new Error(`Некорректный ID релиза: ${releaseId}`);
    }
    const routing = JSON.parse(
        await readFile(routingPath, 'utf8')
    );
    const redirectsAreValid = Array.isArray(routing.redirects)
        && routing.redirects.every((redirect) => (
            redirect?.status === 301
            && isValidPagePath(redirect.from)
            && isValidPagePath(redirect.to)
        ));
    const goneIsValid = Array.isArray(routing.gone)
        && routing.gone.every(isValidPagePath);

    if (!redirectsAreValid || !goneIsValid) {
        throw new Error(`Некорректные правила маршрутизации сайта ${siteSlug}`);
    }

    if (
        !Array.isArray(domains)
        || domains.length === 0
        || domains.some((hostname) => !isValidHostname(hostname))
    ) {
        throw new Error(`Некорректные домены сайта ${siteSlug}`);
    }

    const rules = [];

    for (const [index, redirect] of routing.redirects.entries()) {
        rules.push(`\t\t@redirect${index} path ${quote(redirect.from)}`);
        rules.push(`\t\tredir @redirect${index} ${quote(redirect.to)} 301`);
    }

    if (routing.gone.length > 0) {
        rules.push(`\t\t@gone path ${routing.gone.map(quote).join(' ')}`);
        rules.push('\t\trespond @gone 410');
    }

    const fragment = [
        FRAGMENT_HEADER,
        ...(releaseId ? [`# Kroy release: ${releaseId}`] : []),
        `${domains.map((hostname) => `http://${hostname}:8080`).join(', ')} {`,
        '\troute {',
        '\t\t@vyaz path /admin /admin/* /api /api/* /public /public/* /static /static/* /uploads /uploads/*',
        '\t\treverse_proxy @vyaz host.docker.internal:3000 {',
        '\t\t\theader_up Host {hostport}',
        '\t\t}',
        '\t\t@releaseAssets path /_kroy/releases/*',
        '\t\thandle @releaseAssets {',
        '\t\t\turi strip_prefix /_kroy/releases',
        `\t\t\troot * ${quote(`/srv/${siteSlug}`)}`,
        '\t\t\tfile_server',
        '\t\t}',
        ...rules,
        `\t\troot * ${quote(`/srv/${siteRoot}`)}`,
        '\t\ttry_files {path}/index.html {path}',
        '\t\tfile_server',
        '\t}',
        '}',
        '',
    ].join('\n');
    const fragmentPath = join(OUTPUT_DIR, `${siteSlug}.Caddyfile`);
    const temporaryFragmentPath = `${fragmentPath}.tmp`;
    const outputPath = join(OUTPUT_DIR, 'Caddyfile');
    const temporaryPath = `${outputPath}.tmp`;

    await mkdir(OUTPUT_DIR, { recursive: true });

    try {
        const fragmentNames = (await readdir(OUTPUT_DIR))
            .filter((name) => name.endsWith('.Caddyfile') && name !== `${siteSlug}.Caddyfile`)
            .sort();
        const fragments = [];

        for (const name of fragmentNames) {
            const existingFragment = await readFile(join(OUTPUT_DIR, name), 'utf8');

            if (existingFragment.startsWith(FRAGMENT_HEADER)) {
                fragments.push(existingFragment);
            }
        }

        fragments.push(fragment);
        fragments.sort();

        const config = [
            ...fragments,
            'http://:8080 {',
            '\trespond 404',
            '}',
            '',
        ].join('\n');

        await writeFile(temporaryFragmentPath, fragment);
        await writeFile(temporaryPath, config);
        await execFileAsync(
            'docker',
            [
                'compose',
                '--profile',
                'preview',
                'run',
                '--rm',
                '--no-deps',
                'caddy',
                'caddy',
                'validate',
                '--config',
                '/etc/caddy/Caddyfile.tmp',
                '--adapter',
                'caddyfile',
            ],
            { cwd: ROOT }
        );
        await rename(temporaryFragmentPath, fragmentPath);
        await rename(temporaryPath, outputPath);
    } finally {
        await rm(temporaryFragmentPath, { force: true });
        await rm(temporaryPath, { force: true });
    }

    console.log(`Обновлена конфигурация Caddy: ${outputPath}`);
}
